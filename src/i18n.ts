const dicts: Record<Lang, Record<string, string>> = { zh, en };

let current: Lang = 'zh';

export function resolveLang(pref: string | undefined): Lang {
  if (pref === 'zh' || pref === 'en') return pref;
  const nav = (typeof navigator !== 'undefined' ? navigator.language : 'zh').toLowerCase();
  return nav.startsWith('zh') ? 'zh' : 'en';
}

export function setLang(pref: string | undefined): Lang {
  current = resolveLang(pref);
  return current;
}

export function getLang(): Lang {
  return current;
}

export function t(key: Key | string, vars?: Record<string, string | number>): string {
  let s = dicts[current][key] ?? dicts.zh[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  }
  return s;
}
